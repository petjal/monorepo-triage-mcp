"""Layer 1: Deterministic Repository Scanner, Bloat Pruning, DLP Quarantine, and AST Dependency Extractor."""

import ast
import os
import posixpath
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from monorepo_triage.layer0_invariants import (
    estimate_source_tokens,
    shannon_entropy_bits_per_byte,
    validate_entropy_threshold,
    validate_line_length_limit,
)

FileDisposition = Literal["ACTIVE_SOURCE", "PRUNED_BLOAT", "QUARANTINED_DLP"]

BLOAT_DIR_NAMES: frozenset[str] = frozenset(
    {
        "node_modules",
        "vendor",
        "third_party",
        "target",
        "dist",
        "build",
        ".git",
        ".venv",
        "__pycache__",
    }
)

GENERATED_MARKERS: tuple[str, ...] = (
    "@generated",
    "DO NOT EDIT",
    "auto-generated by",
    "Generated by the protocol buffer compiler",
)

PEM_PATTERN: re.Pattern[str] = re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----")
AWS_KEY_PATTERN: re.Pattern[str] = re.compile(r"AKIA[0-9A-Z]{16}")
GH_TOKEN_PATTERN: re.Pattern[str] = re.compile(r"ghp_[A-Za-z0-9]{36}")

SUPPORTED_SOURCE_EXTENSIONS: frozenset[str] = frozenset(
    {".py", ".ts", ".tsx", ".js", ".jsx", ".java", ".go"}
)

MAX_SOURCE_FILE_BYTES: int = 2 * 1024 * 1024
BINARY_SNIFF_BYTES: int = 8192


@dataclass(frozen=True)
class FileRecord:
    rel_path: str
    module_id: str | None
    disposition: FileDisposition
    reason: str
    estimated_tokens: int
    shannon_entropy: float
    max_line_length: int
    imports: tuple[str, ...]


@dataclass(frozen=True)
class ScanSummary:
    root_path: str
    files: tuple[FileRecord, ...]
    active_tokens: int
    pruned_tokens: int
    quarantined_tokens: int
    token_reduction_ratio: float
    symlink_loops_skipped: tuple[str, ...]
    recommended_exclusions: tuple[str, ...]


def compute_module_id(rel_path: str) -> str:
    """Compute canonical module identifier from relative file path."""
    p = Path(rel_path)
    stem_path = p.with_suffix("")
    parts = list(stem_path.parts)
    if parts and parts[-1] == "__init__":
        parts.pop()
    if not parts:
        return "__init__"
    return ".".join(parts)


def extract_python_imports(text: str, rel_path: str) -> tuple[str, ...]:
    """Extract Python imports using AST, resolving relative imports deterministically."""
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return ()

    parent_parts = list(Path(rel_path).parent.parts)
    extracted: set[str] = set()

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                extracted.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            base_parts: list[str] = []
            if node.level > 0:
                trim = node.level - 1
                if trim <= len(parent_parts):
                    base_parts = parent_parts[: len(parent_parts) - trim]
            if node.module:
                base_parts.extend(node.module.split("."))

            base_mod = ".".join(base_parts)
            if base_mod:
                extracted.add(base_mod)
                for alias in node.names:
                    if alias.name != "*":
                        extracted.add(f"{base_mod}.{alias.name}")

    return tuple(sorted(extracted))


def extract_ts_js_imports(text: str, rel_path: str) -> tuple[str, ...]:
    """Extract TypeScript and JavaScript import targets."""
    extracted: set[str] = set()
    pattern = re.compile(
        r"""(?:import\s+[\w\s{},*]+\s+from\s+['"]([^'"]+)['"]|import\s*\(['"]([^'"]+)['"]\)|import\s+['"]([^'"]+)['"]|require\s*\(['"]([^'"]+)['"]\))"""
    )
    parent_dir = Path(rel_path).parent

    for match in pattern.finditer(text):
        target = next(g for g in match.groups() if g is not None)
        extracted.add(target)
        if target.startswith(("./", "../")):
            norm = os.path.normpath(posixpath.join(parent_dir.as_posix(), target))
            norm_no_ext = re.sub(r"\.(?:ts|tsx|js|jsx)$", "", norm)
            mod = ".".join(Path(norm_no_ext).parts)
            extracted.add(mod)

    return tuple(sorted(extracted))


def extract_go_imports(text: str) -> tuple[str, ...]:
    """Extract Go import paths."""
    extracted: set[str] = set()
    pattern = re.compile(r'import\s*(?:\(([\s\S]*?)\)|"([^"]+)")')
    for match in pattern.finditer(text):
        block, single = match.groups()
        if single:
            extracted.add(single)
            extracted.add(single.replace("/", "."))
        elif block:
            for inner in re.findall(r'"([^"]+)"', block):
                extracted.add(inner)
                extracted.add(inner.replace("/", "."))
    return tuple(sorted(extracted))


def extract_java_imports(text: str) -> tuple[str, ...]:
    """Extract Java import statements."""
    extracted: set[str] = set()
    pattern = re.compile(r"import\s+(?:static\s+)?([a-zA-Z0-9_.]+);")
    for match in pattern.finditer(text):
        extracted.add(match.group(1))
    return tuple(sorted(extracted))


def extract_imports(text: str, rel_path: str, ext: str) -> tuple[str, ...]:
    """Route import extraction to language-specific parser."""
    if ext == ".py":
        return extract_python_imports(text, rel_path)
    if ext in {".ts", ".tsx", ".js", ".jsx"}:
        return extract_ts_js_imports(text, rel_path)
    if ext == ".go":
        return extract_go_imports(text)
    if ext == ".java":
        return extract_java_imports(text)
    return ()


def scan_repository(
    root: Path,
    max_line_length: int = 1000,
    entropy_threshold: float = 5.2,
) -> ScanSummary:
    """Scan repository deterministically, classifying bloat, secrets, and active source."""
    resolved_root = root.resolve()
    valid_max_line = validate_line_length_limit(max_line_length)
    valid_entropy_th = validate_entropy_threshold(entropy_threshold)

    visited_dir_inodes: set[tuple[int, int]] = set()
    root_stat = resolved_root.stat()
    visited_dir_inodes.add((root_stat.st_dev, root_stat.st_ino))

    skipped_symlinks: list[str] = []
    found_files: list[Path] = []

    def collect_files(curr_dir: Path, active_dir_chain: set[tuple[int, int]]) -> None:
        try:
            entries = sorted(curr_dir.iterdir(), key=lambda p: p.name)
        except (OSError, PermissionError):
            return

        for entry in entries:
            rel_str = str(entry.relative_to(resolved_root))
            if entry.is_symlink():
                try:
                    target_resolved = entry.resolve()
                except (OSError, RuntimeError):
                    skipped_symlinks.append(rel_str)
                    continue

                if not target_resolved.is_relative_to(resolved_root):
                    skipped_symlinks.append(rel_str)
                    continue

                if target_resolved.is_dir():
                    # Never recurse into directory symlinks: prevents both ancestor loops
                    # and alphabetical symlink shadowing of canonical physical directories.
                    skipped_symlinks.append(rel_str)
                    continue
                elif target_resolved.is_file():
                    found_files.append(entry)
            elif entry.is_dir():
                try:
                    st = entry.stat()
                    inode_key = (st.st_dev, st.st_ino)
                    if inode_key in active_dir_chain:
                        skipped_symlinks.append(rel_str)
                        continue
                    visited_dir_inodes.add(inode_key)
                    collect_files(entry, active_dir_chain | {inode_key})
                except (OSError, PermissionError):
                    continue
            elif entry.is_file():
                found_files.append(entry)

    collect_files(resolved_root, {(root_stat.st_dev, root_stat.st_ino)})

    records: list[FileRecord] = []
    recommended_set: set[str] = set()

    for file_path in sorted(found_files, key=lambda p: str(p.relative_to(resolved_root))):
        rel_path = str(file_path.relative_to(resolved_root))
        try:
            file_size = file_path.stat().st_size
            if file_size > MAX_SOURCE_FILE_BYTES:
                raw_bytes = b""
                is_oversized = True
            else:
                raw_bytes = file_path.read_bytes()
                is_oversized = False
        except (OSError, PermissionError):
            raw_bytes = b""
            is_oversized = False

        is_binary = is_oversized or (b"\x00" in raw_bytes[:BINARY_SNIFF_BYTES])
        if is_binary:
            est_tokens = max(1, file_size // 4) if is_oversized else max(1, len(raw_bytes) // 4)
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=None,
                    disposition="PRUNED_BLOAT",
                    reason="binary_or_oversized_blob",
                    estimated_tokens=est_tokens,
                    shannon_entropy=shannon_entropy_bits_per_byte(raw_bytes),
                    max_line_length=0,
                    imports=(),
                )
            )
            continue

        text = raw_bytes.decode("utf-8", errors="replace")
        lines = text.splitlines()
        max_line = max((len(l) for l in lines), default=0)
        entropy = shannon_entropy_bits_per_byte(raw_bytes)
        est_tokens = estimate_source_tokens(text)

        # 1. Zero-Trust DLP Quarantine check
        if (
            PEM_PATTERN.search(text)
            or AWS_KEY_PATTERN.search(text)
            or GH_TOKEN_PATTERN.search(text)
        ):
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=None,
                    disposition="QUARANTINED_DLP",
                    reason="dlp_secret_pattern",
                    estimated_tokens=est_tokens,
                    shannon_entropy=entropy,
                    max_line_length=max_line,
                    imports=(),
                )
            )
            continue

        # 2. Vendored and build directory pruning
        path_parts = Path(rel_path).parts[:-1]
        if any(part in BLOAT_DIR_NAMES for part in path_parts):
            if path_parts:
                recommended_set.add(path_parts[0])
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=None,
                    disposition="PRUNED_BLOAT",
                    reason="vendored_or_build_dir",
                    estimated_tokens=est_tokens,
                    shannon_entropy=entropy,
                    max_line_length=max_line,
                    imports=(),
                )
            )
            continue

        # 3. Generated code marker check (first 10 lines)
        header_sample = "\n".join(lines[:10])
        if any(marker in header_sample for marker in GENERATED_MARKERS):
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=None,
                    disposition="PRUNED_BLOAT",
                    reason="generated_code_marker",
                    estimated_tokens=est_tokens,
                    shannon_entropy=entropy,
                    max_line_length=max_line,
                    imports=(),
                )
            )
            continue

        # 4. Minified or high-entropy bundle check
        if max_line > valid_max_line or (max_line > 250 and entropy >= valid_entropy_th):
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=None,
                    disposition="PRUNED_BLOAT",
                    reason="minified_or_high_entropy_blob",
                    estimated_tokens=est_tokens,
                    shannon_entropy=entropy,
                    max_line_length=max_line,
                    imports=(),
                )
            )
            continue

        # 5. Active source vs non-source classification
        ext = file_path.suffix.lower()
        if ext in SUPPORTED_SOURCE_EXTENSIONS:
            mod_id = compute_module_id(rel_path)
            extracted = extract_imports(text, rel_path, ext)
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=mod_id,
                    disposition="ACTIVE_SOURCE",
                    reason="supported_source_language",
                    estimated_tokens=est_tokens,
                    shannon_entropy=entropy,
                    max_line_length=max_line,
                    imports=extracted,
                )
            )
        else:
            records.append(
                FileRecord(
                    rel_path=rel_path,
                    module_id=None,
                    disposition="PRUNED_BLOAT",
                    reason="unsupported_or_non_source",
                    estimated_tokens=est_tokens,
                    shannon_entropy=entropy,
                    max_line_length=max_line,
                    imports=(),
                )
            )

    active_tokens = sum(r.estimated_tokens for r in records if r.disposition == "ACTIVE_SOURCE")
    pruned_tokens = sum(r.estimated_tokens for r in records if r.disposition == "PRUNED_BLOAT")
    quarantined_tokens = sum(
        r.estimated_tokens for r in records if r.disposition == "QUARANTINED_DLP"
    )
    total_tokens = active_tokens + pruned_tokens + quarantined_tokens
    reduction_ratio = (
        round((pruned_tokens + quarantined_tokens) / total_tokens, 4) if total_tokens > 0 else 0.0
    )

    return ScanSummary(
        root_path=str(resolved_root),
        files=tuple(records),
        active_tokens=active_tokens,
        pruned_tokens=pruned_tokens,
        quarantined_tokens=quarantined_tokens,
        token_reduction_ratio=reduction_ratio,
        symlink_loops_skipped=tuple(sorted(skipped_symlinks)),
        recommended_exclusions=tuple(sorted(recommended_set)),
    )
