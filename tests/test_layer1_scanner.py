class TestMinifiedAndHighEntropyBlobs:
    def test_max_line_length_exceeded(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        min_file = repo / "bundle.js"
        # 1200 chars on a single line
        min_file.write_text("var a=" + "1+" * 600 + "0;\n")

        summary = scan_repository(repo, max_line_length=500)
        rec = summary.files[0]
        assert rec.disposition == "PRUNED_BLOAT"
        assert rec.reason == "minified_or_high_entropy_blob"

    def test_high_entropy_bundle_blob(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        # High entropy base64 pseudo-data > 250 line length
        import base64
        pseudo_packed = base64.b64encode(bytes(range(256)) * 2).decode("ascii")
        bundle = repo / "compressed_asset.js"
        bundle.write_text(f"/* data */ var pack = '{pseudo_packed}';\n")

        summary = scan_repository(repo, max_line_length=2000, entropy_threshold=5.0)
        rec = summary.files[0]
        assert rec.disposition == "PRUNED_BLOAT"
        assert rec.reason == "minified_or_high_entropy_blob"


