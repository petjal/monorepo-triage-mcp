class TestSymlinkAndConfinementProtection:
    def test_symlink_loop_and_outside_skip(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        src = repo / "src"
        src.mkdir()
        (src / "app.py").write_text("print('hello')\n")

        # Create outside file and escaping symlink
        outside = tmp_path / "outside.py"
        outside.write_text("print('outside')\n")
        (src / "outside_link.py").symlink_to(outside)

        # Create directory symlink loop (pointing to repo root)
        (src / "loop_link").symlink_to(repo)

        summary = scan_repository(repo)
        assert len(summary.symlink_loops_skipped) >= 2
        # Escaping link and recursive loop must be in symlink_loops_skipped
        skipped_names = [Path(s).name for s in summary.symlink_loops_skipped]
        assert "outside_link.py" in skipped_names
        assert "loop_link" in skipped_names

        # Confined active source must be present
        active_rel = [f.rel_path for f in summary.files if f.disposition == "ACTIVE_SOURCE"]
        assert "src/app.py" in active_rel


