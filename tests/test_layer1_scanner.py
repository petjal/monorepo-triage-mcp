class TestSymlinkAndConfinementProtection:
    def test_symlink_loop_and_outside_skip(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        src = repo / "src"
        src.mkdir()
        (src / "app.py").write_text("print('hello')\n")

        # Create outside file and escaping symlink
        outside = tmp_path / "outside.py"
        outside.write_text("print('outside')\n")
        (src / "outside_link.py").symlink_to(outside)

        # Create directory symlink loop (pointing to repo root)
        (src / "loop_link").symlink_to(repo)

        summary = scan_repository(repo)
        assert len(summary.symlink_loops_skipped) >= 2
        # Escaping link and recursive loop must be in symlink_loops_skipped
        skipped_names = [Path(s).name for s in summary.symlink_loops_skipped]
        assert "outside_link.py" in skipped_names
        assert "loop_link" in skipped_names

        # Confined active source must be present
        active_rel = [f.rel_path for f in summary.files if f.disposition == "ACTIVE_SOURCE"]
        assert "src/app.py" in active_rel


class TestBloatDirectoryPruning:
    def test_vendor_and_build_dirs_pruned(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        (repo / "src").mkdir()
        (repo / "src" / "core.py").write_text("x = 1\n")

        (repo / "node_modules" / "pkg").mkdir(parents=True)
        (repo / "node_modules" / "pkg" / "index.js").write_text("module.exports = {};\n")

        (repo / "vendor" / "lib").mkdir(parents=True)
        (repo / "vendor" / "lib" / "dep.py").write_text("def vendored(): pass\n")

        (repo / "target" / "debug").mkdir(parents=True)
        (repo / "target" / "debug" / "out.rs").write_text("fn main() {}\n")

        summary = scan_repository(repo)
        by_path = {f.rel_path: f for f in summary.files}

        assert by_path["src/core.py"].disposition == "ACTIVE_SOURCE"
        assert by_path["node_modules/pkg/index.js"].disposition == "PRUNED_BLOAT"
        assert by_path["node_modules/pkg/index.js"].reason == "vendored_or_build_dir"
        assert by_path["vendor/lib/dep.py"].disposition == "PRUNED_BLOAT"
        assert by_path["vendor/lib/dep.py"].reason == "vendored_or_build_dir"
        assert by_path["target/debug/out.rs"].disposition == "PRUNED_BLOAT"
        assert by_path["target/debug/out.rs"].reason == "vendored_or_build_dir"


