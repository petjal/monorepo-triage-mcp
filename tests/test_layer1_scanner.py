class TestActiveSourceASTImportExtraction:
    def test_python_relative_and_absolute_imports(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        pkg = repo / "app" / "services"
        pkg.mkdir(parents=True)
        (repo / "app" / "__init__.py").write_text("")
        (pkg / "__init__.py").write_text("")
        (repo / "app" / "models.py").write_text("class User: pass\n")
        (repo / "app" / "common.py").write_text("def log(): pass\n")

        worker = pkg / "worker.py"
        worker.write_text(
            "import os\n"
            "from . import auth\n"
            "from ..models import User\n"
            "from app.common import log\n"
        )

        summary = scan_repository(repo)
        by_mod = {f.module_id: f for f in summary.files if f.disposition == "ACTIVE_SOURCE"}

        assert "app.services.worker" in by_mod
        assert "app.models" in by_mod
        assert "app.common" in by_mod
        assert "app.services" in by_mod

        worker_rec = by_mod["app.services.worker"]
        # worker relative import 1 level up is app.services.auth
        # relative import 2 levels up is app.models
        # absolute import is app.common
        assert any("app.models" in imp for imp in worker_rec.imports)
        assert any("app.common" in imp for imp in worker_rec.imports)

    def test_multi_language_import_extraction(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()

        ts_file = repo / "frontend" / "app.ts"
        ts_file.parent.mkdir(parents=True)
        ts_file.write_text(
            "import { useState } from 'react';\n"
            "import { AuthProvider } from './auth';\n"
            "import { apiClient } from '../common/client';\n"
        )

        go_file = repo / "cmd" / "server" / "main.go"
        go_file.parent.mkdir(parents=True)
        go_file.write_text(
            'package main\n\nimport (\n\t"fmt"\n\t"myrepo/pkg/router"\n)\n\nfunc main() {}\n'
        )

        java_file = repo / "src" / "com" / "example" / "Main.java"
        java_file.parent.mkdir(parents=True)
        java_file.write_text(
            "package com.example;\n"
            "import java.util.List;\n"
            "import com.example.service.UserService;\n\n"
            "public class Main {}\n"
        )

        summary = scan_repository(repo)
        by_path = {f.rel_path: f for f in summary.files}

        ts_rec = by_path["frontend/app.ts"]
        assert ts_rec.disposition == "ACTIVE_SOURCE"
        assert any("frontend.auth" in imp or "./auth" in imp for imp in ts_rec.imports)

        go_rec = by_path["cmd/server/main.go"]
        assert go_rec.disposition == "ACTIVE_SOURCE"
        assert any("myrepo/pkg/router" in imp or "myrepo.pkg.router" in imp for imp in go_rec.imports)

        java_rec = by_path["src/com/example/Main.java"]
        assert java_rec.disposition == "ACTIVE_SOURCE"
        assert any("com.example.service.UserService" in imp for imp in java_rec.imports)


class TestScanSummaryMetrics:
    def test_reduction_ratio_and_token_accounting(self, tmp_path: Path) -> None:
        repo = tmp_path / "repo"
        repo.mkdir()
        (repo / "main.py").write_text("print('hello active source')\n")

        (repo / "node_modules").mkdir()
        (repo / "node_modules" / "huge.js").write_text("var x = 1;\n" * 500)

        (repo / "key.pem").write_text("-----BEGIN EC PRIVATE KEY-----\nabc\n-----END EC PRIVATE KEY-----\n")

        summary = scan_repository(repo)
        assert summary.active_tokens > 0
        assert summary.pruned_tokens > 0
        assert summary.quarantined_tokens > 0
        assert 0.0 < summary.token_reduction_ratio <= 1.0
        assert "node_modules" in summary.recommended_exclusions
